
import { api } from "./api";


// ============================================================
// CASE DTO
// ============================================================

export interface CaseDto {

    id?: string;

    name: string;

    title?: string;

    description?: string;

    status: string;

    createdAt?: string;

    updatedAt?: string;


    // ========================================================
    // GRAPH DATA
    // ========================================================

    nodes?: any[];

    edges?: any[];

    events?: any[];


    // ========================================================
    // OPTIONAL CASE DATA
    // ========================================================

    entities?: any[];

    relationships?: any[];

    evidence?: any[];

    documents?: any[];

    locations?: any[];

    communications?: any[];

    notes?: any[];

}


// ============================================================
// CASE API
// ============================================================

export const caseApi = {

    // ========================================================
    // GET ALL CASES
    // ========================================================

    getAll: () =>
        api.get<CaseDto[]>(
            "/cases"
        ),


    // ========================================================
    // GET CASE BY ID
    // ========================================================

    getById: (
        id: string
    ) =>
        api.get<CaseDto>(
            `/cases/${id}`
        ),


    // ========================================================
    // CREATE CASE
    // ========================================================

    create: (
        data: CaseDto
    ) =>
        api.post<CaseDto>(
            "/cases",
            data
        ),


    // ========================================================
    // UPDATE CASE
    // ========================================================

    update: (
        id: string,
        data: CaseDto
    ) =>
        api.put<CaseDto>(
            `/cases/${id}`,
            data
        ),


    // ========================================================
    // DELETE CASE
    // ========================================================

    delete: (
        id: string
    ) =>
        api.delete<void>(
            `/cases/${id}`
        )

};

